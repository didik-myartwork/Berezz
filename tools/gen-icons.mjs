const kebab = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function toMarkup(nodes) {
  return nodes.map(([tag, attrs]) => {
    const parts = Object.entries(attrs)
      .filter(([k]) => k !== 'key')
      .map(([k, v]) => `${kebab(k)}="${v}"`);
    return `<${tag} ${parts.join(' ')}/>`;
  }).join('');
}

const lines = Object.entries(ICONS).map(([name, source]) => {
  const nodes = hugeicons[source];
  if (!nodes) throw new Error(`Ikon tidak ditemukan: ${source}`);
  return `  ${name}: '${toMarkup(nodes)}',`;
});

writeFileSync('src/icons.ts', `/**
 * Hugeicons (free, stroke-rounded) — generated by tools/gen-icons.mjs.
 * Do not edit by hand; add names in the generator instead.
 */

const PATHS = {
${lines.join('\n')}
} as const;

export type IconName = keyof typeof PATHS;

/** Inline SVG markup. Decorative by default; pass a label when the icon carries meaning alone. */
export function icon(name: IconName, size = 16, label = ''): string {
  const a11y = label ? \`role="img" aria-label="\${label}"\` : 'aria-hidden="true" focusable="false"';
  return \`<svg class="i" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" \${a11y}>\${PATHS[name]}</svg>\`;
}

export function hasIcon(name: string): name is IconName {
  return Object.prototype.hasOwnProperty.call(PATHS, name);
}
`);

